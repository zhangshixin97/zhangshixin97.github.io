def main():
    docs = {}
    for slug, d in DOCS.items():
        entry = {
            "title": d["title"],
            "markdown": d["markdown"].strip(),
            "download": f"/skills/{slug}.zip",
        }
        if d.get("author"):
            entry["author"] = d["author"]
        docs[slug] = entry
    out = (
        "// 本文件由 tools/generate_skill_docs.py 生成，勿手改；\n"
        "// 改说明文案请改脚本里的 DOCS 后重新运行。\n"
        "export interface SkillDocEntry { title: string; markdown: string; download: string; author?: string; }\n"
        "export const skillDocs: Record<string, SkillDocEntry> = "
        + json.dumps(docs, ensure_ascii=False, indent=2)
        + ";\n"
    )
    target = ROOT / "src" / "skillDocs.ts"
    target.write_text(out, encoding="utf-8")
    print(f"已生成 {target}，共 {len(docs)} 个技能说明")

if __name__ == "__main__":
    main()
